// Генерирует синюю тему для мальчиков из розовых стилей index.html.
// Запуск после правки стилей: node scripts/boy-theme.js
// Тема включается классом theme-boy на <html> (ставит app.js по профилю ребёнка).
const fs = require('fs');
const path = require('path');
const file = path.join(__dirname, '..', 'index.html');
let html = fs.readFileSync(file, 'utf8');

const MAP = {
    '#ec4899': '#3b82f6', '#db2777': '#2563eb', '#f472b6': '#60a5fa', '#fbcfe8': '#bfdbfe',
    '#fce7f3': '#dbeafe', '#fdf2f8': '#eff6ff', '#fecdd3': '#bfdbfe', '#fff1f2': '#eff6ff',
    '#f9a8d4': '#93c5fd', '#a21caf': '#1d4ed8', '#701a75': '#1e3a8a', '#86198f': '#1e40af',
    '#c084fc': '#38bdf8', '#a855f7': '#0ea5e9', '#9333ea': '#0284c7', '#7e22ce': '#1d4ed8',
    '#e9d5ff': '#bae6fd', '#f3e8ff': '#e0f2fe', '#faf5ff': '#f0f9ff', '#f5f3ff': '#f0f9ff',
    '#fdf4ff': '#f0f9ff', '#581c87': '#0c4a6e', '#6b21a8': '#075985', '#be185d': '#1e40af',
    '#fff7fb': '#f0f9ff', '#fffdfd': '#f8fbff', '#c4a5c9': '#9fb7d3', '#dbeafe': '#ccfbf1',
    'rgba(236, 72, 153,': 'rgba(59, 130, 246,', 'rgba(192, 132, 252,': 'rgba(56, 189, 248,',
    'rgba(168, 85, 247,': 'rgba(14, 165, 233,'
};
const keys = Object.keys(MAP).sort((a, b) => b.length - a.length);
const re = new RegExp(keys.map(k => k.replace(/[()]/g, '\\$&')).join('|'), 'gi');
const hasColor = s => { re.lastIndex = 0; return re.test(s); };
const recolor = s => s.replace(re, m => MAP[m.toLowerCase()]);

const START = '/* ===== BOY THEME (generated by scripts/boy-theme.js) ===== */';
const END = '/* ===== END BOY THEME ===== */';
html = html.replace(new RegExp('\\s*' + START.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&') + '[\\s\\S]*?' + END.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')), '');

const css = html.slice(html.indexOf('<style>') + 7, html.indexOf('</style>'));
const out = [];
let i = 0;
while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const selector = css.slice(i, open).replace(/\/\*[\s\S]*?\*\//g, '').trim();
    // найти парную скобку
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    const body = css.slice(open + 1, j - 1);
    i = j;
    if (selector.startsWith('@')) continue;             // @keyframes, @media — без цветов темы
    if (/\.girl/.test(selector)) continue;              // кнопка «Девочка» остаётся розовой
    const decls = body.split(';').map(d => d.trim()).filter(d => d && hasColor(d));
    if (!decls.length) continue;
    const sel = selector.split(',').map(s => s.trim()).map(s =>
        s === ':root' ? 'html.theme-boy' : s === 'html' ? 'html.theme-boy' : 'html.theme-boy ' + s).join(', ');
    out.push(`        ${sel} { ${decls.map(recolor).join('; ')}; }`);
}
// украшения для мальчиков
out.push("        html.theme-boy .category-card::before { content: '★'; color: #bfdbfe; }");
out.push("        html.theme-boy .game-container::after { content: '⚽'; }");

const block = `\n        ${START}\n${out.join('\n')}\n        ${END}\n`;
html = html.replace('    </style>', block + '    </style>');
fs.writeFileSync(file, html);
console.log('boy theme rules:', out.length);
